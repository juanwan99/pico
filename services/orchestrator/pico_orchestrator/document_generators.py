"""Deterministic allowlist document generators (HTML / DOCX / PPTX).

Pure stdlib. Binary OOXML is real ZIP packages, never text with a renamed suffix.
"""

from __future__ import annotations

import html
import io
import zipfile
from xml.sax.saxutils import escape


def _require_marker(marker: str) -> str:
    value = (marker or "").strip()
    if not value:
        raise ValueError("marker is required")
    if len(value) > 200:
        raise ValueError("marker exceeds 200 characters")
    if any(ord(ch) < 32 for ch in value):
        raise ValueError("marker contains control characters")
    return value


def build_html_document(
    *,
    title: str,
    marker: str,
    body: str | None = None,
) -> bytes:
    """HTML bytes with unique marker, no external scripts/styles."""
    marker = _require_marker(marker)
    safe_title = html.escape((title or "Pico HTML").strip() or "Pico HTML")
    safe_marker = html.escape(marker)
    safe_body = html.escape((body or "").strip() or f"Pico HTML deliverable · {marker}")
    # CSP meta + no script tags + no external links. Preview also sandboxes.
    doc = f"""<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8" />
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src data:; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'; frame-ancestors 'none';" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>{safe_title}</title>
  <style>
    body {{ font-family: system-ui, sans-serif; margin: 1.5rem; color: #1a1a1a; line-height: 1.5; }}
    .marker {{ font-family: ui-monospace, monospace; background: #f3f4f6; padding: 0.25rem 0.5rem; border-radius: 0.25rem; }}
  </style>
</head>
<body>
  <h1>{safe_title}</h1>
  <p>标记：<span class="marker" data-pico-marker="{safe_marker}">{safe_marker}</span></p>
  <p>{safe_body}</p>
</body>
</html>
"""
    return doc.encode("utf-8")


def build_docx_document(
    *,
    title: str,
    marker: str,
    body: str | None = None,
) -> bytes:
    """Minimal valid OOXML DOCX (ZIP with Content_Types + word/document.xml)."""
    marker = _require_marker(marker)
    heading = escape((title or "Pico DOCX").strip() or "Pico DOCX")
    paragraph = escape((body or "").strip() or f"Pico DOCX deliverable · {marker}")
    marker_xml = escape(marker)

    content_types = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>
"""
    rels = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>
"""
    document = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:body>
    <w:p><w:r><w:t>{heading}</w:t></w:r></w:p>
    <w:p><w:r><w:t>标记：{marker_xml}</w:t></w:r></w:p>
    <w:p><w:r><w:t>{paragraph}</w:t></w:r></w:p>
    <w:sectPr/>
  </w:body>
</w:document>
"""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("[Content_Types].xml", content_types)
        zf.writestr("_rels/.rels", rels)
        zf.writestr("word/document.xml", document)
    return buf.getvalue()


